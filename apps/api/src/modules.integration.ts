import { projectMetrics } from "../../../packages/shared/src/projectMetrics";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { emptyStudentProfile, studentHistorySchema, type DemoState } from "../../../packages/shared/src/model";

export async function verifyModules(origin: string, headers: Record<string, string>, teacherHeaders: Record<string, string>) {
  const read = async (): Promise<DemoState> => (await fetch(origin + "/api/state", { headers })).json();
  const send = async (command: unknown, status = 201) => {
    const response = await fetch(origin + "/api/commands", { method: "POST", headers,
      body: JSON.stringify({ command, requestId: randomUUID() }) });
    const body = await response.json();
    assert.equal(response.status, status, JSON.stringify({command,body}));
  };
  await send({ type: "student.create", student: { ...emptyStudentProfile(), name: "模块专项", chineseName: "模块专项" } });
  let state = await read();
  const student = state.students.find(s => s.chineseName === "模块专项")!;
  await send({ type: "student.details.update", id: student.id, patch: { personality: "主动表达" }, expected: { personality: student.personality } });
  assert.equal((await read()).students.find(s => s.id === student.id)!.personality, "主动表达");
  await send({ type: "student.details.update", id: student.id, patch: { personality: "过期写入" }, expected: { personality: student.personality } }, 400);
  assert.equal((await read()).students.find(s => s.id === student.id)!.personality, "主动表达");
  await send({ type: "task.add", studentId: student.id, title: "模块回访", owner: "验收", note: "真实持久化" });
  const task = (await read()).tasks.find(t => t.studentId === student.id && t.title === "模块回访")!;
  assert.ok(task);
  await send({ type: "task.complete", id: task.id, result: "已联系" });
  assert.equal((await read()).tasks.find(t => t.id === task.id)!.result, "已联系");
  await send({ type: "service.add", studentId: student.id, content: "家长回访完成", stars: 5 });
  assert.ok((await read()).events.some(e => e.studentId === student.id && JSON.stringify(e).includes("家长回访完成")));
  state = await read();
  await send({ type: "credit.deduct", studentId: student.id, units: 1, reason: "余额不足回滚" }, 400);
  const after = await read();
  assert.deepEqual(after.credits, state.credits);
  assert.equal(after.students.find(s => s.id === student.id)!.balance, 0);
  const materialId = randomUUID();
  await send({ type: "catalog.save", entry: { id: materialId, type: "教材", name: "专项教材", detail: "持久化后引用", enabled: true } });
  assert.ok((await read()).catalog.some(c => c.id === materialId));
  await send({ type: "student.details.update", id: student.id, patch: { material: "专项教材" }, expected: { material: student.material } });
  assert.equal((await read()).students.find(s => s.id === student.id)!.material, "专项教材");
  await send({ type: "student.import", mode: "skip", batchId: randomUUID(), students: [{ ...emptyStudentProfile(), name: "期初专项", chineseName: "期初专项" }] });
  const opening = (await read()).students.find(s => s.chineseName === "期初专项")!;
  await send({ type: "student.balance.open", id: opening.id, balance: 12, reason: "账单核对" });
  assert.equal((await read()).students.find(s => s.id === opening.id)!.balance, 12);
  await send({ type: "student.balance.open", id: opening.id, balance: 12, reason: "重复核对" }, 400);
  state = await read();
  const sourceTeacher = state.teachers[0];
  const teacherA = { ...sourceTeacher, id: randomUUID(), name: "专项老师甲", phone: "13911110001", classInUid: "99111", status: "在职" };
  const teacherB = { ...sourceTeacher, id: randomUUID(), name: "专项老师乙", phone: "13911110002", classInUid: "99112", status: "在职" };
  await send({ type: "teacher.save", teacher: teacherA });
  await send({ type: "teacher.save", teacher: teacherB });
  await send({ type: "student.bindClassIn", id: opening.id, phone: "13911110003", uid: "99113" });
  await send({ type: "lesson.schedule", studentId: opening.id, teacherId: teacherA.id, slots: [{ date: "2026-12-21", time: "10:00" }], duration: 25, kind: "临时课", material: "专项教材", confirmedTeacher: true });
  let lesson = (await read()).lessons.find(l => l.studentId === opening.id)!;
  await send({ type: "lesson.reschedule", id: lesson.id, date: "2026-12-22", time: "11:00", teacherId: teacherA.id, reason: "调整时间", confirmedTeacher: true });
  lesson = (await read()).lessons.find(l => l.id === lesson.id)!;
  assert.equal(lesson.date, "2026-12-22");
  assert.equal(lesson.sync, "处理中");
  await send({ type: "lesson.changeTeacher", studentId: opening.id, teacherId: teacherB.id, from: "2026-12-22", reason: "换师专项", confirmedTeacher: true });
  assert.equal((await read()).lessons.find(l => l.id === lesson.id)!.teacherId, teacherB.id);
  await send({ type: "teacher.leave", teacherId: teacherB.id, start: "2026-12-22T00:00", end: "2026-12-22T23:59", reason: "请假专项", cancelLessons: false });
  state = await read();
  assert.ok(state.leaves.some(l => l.teacherId === teacherB.id));
  assert.equal(state.lessons.find(l => l.id === lesson.id)!.leaveFlag, true);
  await send({ type: "teacher.offboard", teacherId: teacherB.id, confirmName: teacherB.name, reason: "离职专项" });
  state = await read();
  assert.equal(state.teachers.find(t => t.id === teacherB.id)!.status, "已离职");
  assert.equal(state.lessons.find(l => l.id === lesson.id)!.status, "已取消");
  assert.equal(state.students.find(s => s.id === opening.id)!.balance, 12);
  for (const body of [{ phone: "13911110003", password: "Testing123!", consent: false, role: "student" }, { phone: "13911110003", consent: true, role: "student" }]) {
    const response = await fetch(origin + "/api/classin-account", { method: "POST", headers, body: JSON.stringify(body) });
    assert.equal(response.status, 400);
  }
  const roleId = randomUUID();
  await send({ type: "role.save", role: { id: roleId, name: "专项客服", description: "仅客服处理", scope: "全部", permissions: ["feedback.view", "feedback.process"] } });
  const loginName = "customer-" + randomUUID();
  await send({ type: "account.save", account: { id: randomUUID(), name: "专项客服", phone: loginName, roleId, scope: "全部", enabled: true }, initialPassword: "Customer123!" });
  const loginResponse = await fetch(origin + "/api/session", { method: "POST", headers: { "content-type": "application/json", origin: headers.origin }, body: JSON.stringify({ login: loginName, password: "Customer123!" }) });
  assert.equal(loginResponse.status, 201);
  const identity = await loginResponse.json();
  const customerHeaders = { ...headers, cookie: loginResponse.headers.get("set-cookie")!.split(";")[0], "x-csrf-token": identity.csrfToken };
  const feedback = (await read()).feedback[0];
  for (const [type, expectedStatus] of [["feedback.customer", 201], ["feedback.tm", 400]]) {
    const response = await fetch(origin + "/api/commands", { method: "POST", headers: customerHeaders, body: JSON.stringify({ requestId: randomUUID(), command: { type, id: feedback.id, progress: "待TM判定", result: "处理成功", note: "跨权限专项", jointVerdict: "二星", date: "2026-11-18" } }) });
    assert.equal(response.status, expectedStatus, await response.text());
  }
  await send({ type: "feedback.tm", id: feedback.id, result: "处理成功", jointVerdict: "二星", date: "2026-11-18", note: "管理端判定" });
  assert.ok(JSON.stringify((await read()).feedback.find(f => f.id === feedback.id)).includes("管理端判定"));
  await send({ type: "feedback.measures", id: feedback.id, measures: ["警告"], amount: 0, separateDeduction: false, deductionConfirmed: false, note: "措施来源验收" });
  assert.ok((await read()).actions.some(a => a.feedbackId === feedback.id && a.teacherId === feedback.teacherId && a.type === "警告"));
  const history = studentHistorySchema.parse((await read()).students.find(s => s.id === student.id));
  await send({ type: "student.history.update", id: student.id, history: { ...history, legacyComplaints: "历史投诉已核对" }, reason: "导入历史更正" });
  state = await read();
  assert.equal(state.students.find(s => s.id === student.id)!.legacyComplaints, "历史投诉已核对");
  assert.ok(state.events.some(e => e.studentId === student.id && JSON.stringify(e).includes("导入历史更正")));
  const lock = { type: "slot.lock", studentId: opening.id, slots: [{ teacherId: teacherA.id, date: "2026-12-28", time: "10:00" }], duration: 25, expiresAt: new Date(Date.now() + 1200).toISOString() };
  await send(lock);
  await send({ ...lock, studentId: student.id }, 400);
  await new Promise(resolve => setTimeout(resolve, 1250));
  await send({ ...lock, studentId: student.id, expiresAt: new Date(Date.now() + 60000).toISOString() });
  state = await read();
  assert.equal(state.slotLocks?.filter(l => l.teacherId === teacherA.id && l.date === "2026-12-28").length, 1);
  assert.equal(state.slotLocks?.find(l => l.teacherId === teacherA.id && l.date === "2026-12-28")?.studentId, student.id);
  await send({ type: "slot.release", studentId: student.id });
  assert.equal((await read()).slotLocks?.some(l => l.studentId === student.id), false);
  await send({ type: "teacher.save", teacher: { ...(await read()).teachers.find(t => t.id === teacherA.id), availabilityNote: "老师可用时间专项", availability: [{ day: 1, start: "09:00", end: "18:00" }] } });
  assert.equal((await read()).teachers.find(t => t.id === teacherA.id)!.availabilityNote, "老师可用时间专项");
  const own: DemoState = await (await fetch(origin + "/api/state", { headers: teacherHeaders })).json();
  const ownTeacher = own.teachers[0];
  const savedAvailability = await fetch(origin + "/api/commands", { method: "POST", headers: teacherHeaders, body: JSON.stringify({ requestId: randomUUID(), command: { type: "teacher.save", teacher: { ...ownTeacher, availabilityNote: "老师自助提交专项" } } }) });
  assert.equal(savedAvailability.status, 201, await savedAvailability.text());
  assert.equal((await read()).teachers.find(t => t.id === ownTeacher.id)!.availabilityNote, "老师自助提交专项");
  assert.ok(own.payroll.every(p => p.teacherId === ownTeacher.id && p.status !== "待确认"));
  assert.ok((own.settlements ?? []).every(p => p.teacherId === ownTeacher.id));
  assert.equal(own.payTerms?.length ?? 0, 0);
  const image = "data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Wl6nZsAAAAASUVORK5CYII=";
  const upload = await fetch(origin + "/api/files", { method: "POST", headers, body: JSON.stringify({ data: image }) });
  assert.equal(upload.status, 201);
  const file = await upload.json();
  await send({ type: "feedback.edit", id: feedback.id, feedback: { ...feedback, screenshots: [{ id: randomUUID(), name: "跨账号截图", dataUrl: file.url }] } });
  const customerState: DemoState = await (await fetch(origin + "/api/state", { headers: customerHeaders })).json();
  assert.equal(customerState.feedback.find(f => f.id === feedback.id)!.screenshots[0].dataUrl, file.url);
  assert.equal((await fetch(origin + file.url, { headers: customerHeaders })).status, 200);
  assert.equal((await fetch(origin + file.url)).status, 401);
  const channel = { id: randomUUID(), type: "渠道", name: "指标渠道", detail: "", enabled: true };
  const project = { id: randomUUID(), type: "项目", name: "指标项目", channelIds: [channel.id], detail: "", enabled: true, monthlyLessons: 8 };
  await send({ type: "catalog.save", entry: channel });
  await send({ type: "catalog.save", entry: project });
  const metricStudent = (await read()).students.find(s => s.id === student.id)!;
  await send({ type: "student.details.update", id: student.id, patch: { channel: channel.name, project: project.name }, expected: { channel: metricStudent.channel, project: metricStudent.project } });
  const metricState = await read();
  const beforeTarget = projectMetrics(metricState, metricState.students.find(s => s.id === student.id)!, "2026-10").target;
  await send({ type: "catalog.save", entry: { ...project, monthlyLessons: 12 } });
  const updatedMetrics = await read();
  assert.equal(projectMetrics(updatedMetrics, updatedMetrics.students.find(s => s.id === student.id)!, "2026-10").target, beforeTarget);
  assert.equal(updatedMetrics.catalog.find(c => c.id === project.id)!.targetHistory?.at(-1)?.lessons, 12);
  await send({ type: "catalog.save", entry: { ...channel, enabled: false } });
  await send({ type: "rules.save", rules: updatedMetrics.rules });
  assert.deepEqual((await read()).rules, updatedMetrics.rules);
  console.log("PASS module API profile persistence/stale write rejection, tasks completion, service follow-up, insufficient balance transaction unchanged");
}
