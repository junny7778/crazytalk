import { z } from "zod";
import { accountPasswordSchema } from "./accountPassword";
import {
  studentSchema,
  studentProfileSchema,
  studentEditableSchema,
  studentHistorySchema,
  teacherSchema,
  scheduleIntentSchema,
  studentSurveyAnswers,
  payTermsSchema,
  feedbackSchema,
  feedbackDetailsInputSchema,
  lessonSchema,
  roleSchema,
  accountSchema,
  catalogSchema,
  reportSchema,
  leaveSchema,
  stateSchema,
  type Command,
} from "./model";

const text = z.string();
const id = text.min(1);
const date = text.regex(/^\d{4}-\d{2}-\d{2}$/);
const time = text.regex(/^([01]\d|2[0-3]):[0-5]\d$/);
const number = z.number().finite();
const nonnegative = number.nonnegative();
const positive = number.positive();
const duration = z.union([
  z.literal(25),
  z.literal(50),
  z.literal(55),
  z.literal(120),
]);
const feedbackInput = z.union([
  feedbackDetailsInputSchema,
  feedbackSchema.pick({
    studentId: true,
    teacherId: true,
    lessonId: true,
    rating: true,
    category: true,
    content: true,
  }),
]);

// API input is parsed once here. The domain receives a typed command.
export const commandSchema = z.discriminatedUnion("type", [
  z.object({
    type: z.literal("referral.add"),
    studentId: id,
    referrerStudentId: id,
    date,
    note: text,
  }),
  z.object({
    type: z.literal("task.add"),
    studentId: id,
    title: id,
    owner: id,
    dueDate: date.optional(),
    note: text.optional(),
  }),
  z.object({ type: z.literal("task.complete"), id, result: text.optional() }),
  z.object({
    type: z.literal("student.reminder.preview"),
    studentId: id,
    kind: z.enum(["balance", "attendance"]),
    threshold: nonnegative,
    lookbackDays: positive.optional(),
  }),
  z.object({
    type: z.literal("student.courseReminder.preview"),
    studentId: id,
    lessonId: id,
    kind: z.enum(["before", "feedback"]),
  }),
  z.object({
    type: z.literal("student.details.update"),
    id,
    patch: studentEditableSchema.partial(),
    expected: studentEditableSchema.partial(),
  }),
  z.object({
    type: z.literal("student.history.update"),
    id,
    history: studentHistorySchema,
    reason: id,
  }),
  z.object({
    type: z.literal("student.scheduleIntent.update"),
    studentId: id,
    intent: scheduleIntentSchema,
  }),
  z.object({
    type: z.literal("slot.lock"),
    studentId: id,
    slots: z.array(z.object({ teacherId: id, date, time })).min(1),
    duration,
    expiresAt: text.datetime(),
  }),
  z.object({ type: z.literal("slot.release"), studentId: id }),
  z.object({
    type: z.literal("lesson.incident"),
    id,
    minutes: nonnegative.optional(),
    reason: id,
    note: text,
  }),
  z.object({
    type: z.literal("lesson.attendance"),
    id,
    person: z.enum(["学员", "老师"]),
    result: z.enum(["未到堂", "到堂", "缺席"]),
    at: text.datetime(),
  }),
  z.object({
    type: z.literal("lesson.notice"),
    id,
    sent: z.boolean(),
    error: text,
  }),
  z.object({ type: z.literal("pay.terms"), terms: payTermsSchema }),
  z.object({
    type: z.literal("pay.freeze"),
    teacherId: id,
    month: text.regex(/^\d{4}-(0[1-9]|1[0-2])$/),
  }),
  z.object({
    type: z.literal("survey.issue"),
    id,
    token: text.optional(),
    secret: text.optional(),
  }),
  z.object({
    type: z.literal("survey.submit"),
    token: id,
    submittedAt: text.optional(),
    nameEdited: z.boolean().optional(),
    answers: studentSurveyAnswers,
  }),
  z.object({
    type: z.literal("order.join"),
    orderId: id,
    studentId: id,
    bindAccountId: id.optional(),
  }),
  z.object({
    type: z.literal("order.buy"),
    id,
    studentId: id,
    studentIds: z.array(id).min(1),
    units: z.union([z.literal(72), z.literal(144)]),
    date,
    kind: id,
    note: text,
  }),
  z.object({ type: z.literal("student.bindClassIn"), id, phone: z.string(), uid: id }),
  z.object({
    type: z.literal("student.profile"),
    id,
    profile: studentProfileSchema,
  }),
  z.object({
    type: z.literal("student.import"),
    batchId: id.optional(),
    students: z.array(studentProfileSchema),
    mode: z.enum(["skip", "update"]),
  }),
  z.object({
    type: z.literal("student.balance.open"),
    id,
    balance: nonnegative,
    reason: id,
  }),
  z.object({
    type: z.literal("student.create"),
    student: studentProfileSchema,
  }),
  z.object({
    type: z.literal("student.edit"),
    id,
    patch: studentSchema
      .pick({
        name: true,
        chineseName: true,
        phone: true,
        owner: true,
        ownerAccountId: true,
        level: true,
        material: true,
        unit: true,
        preferences: true,
        goal: true,
      })
      .partial(),
  }),
  z.object({
    type: z.literal("credit.deduct"),
    orderId: id.optional(),
    studentId: id,
    units: positive,
    reason: id,
  }),
  z.object({
    type: z.literal("credit.add"),
    purchaseId: id.optional(),
    orderId: id.optional(),
    studentId: id,
    units: positive,
    kind: id,
    note: text,
    date: date.optional(),
    amount: nonnegative.optional(),
    feedbackId: id.optional(),
    referralId: id.optional(),
  }),
  z.object({
    type: z.literal("student.lifecycle"),
    studentId: id,
    status: studentSchema.shape.status,
    reason: id,
    keepSlots: z.boolean().optional(),
  }),
  z.object({
    type: z.literal("service.add"),
    studentId: id,
    content: id,
    satisfaction: text.optional(),
    stars: number.int().min(1).max(5).optional(),
    stage: text.optional(),
    evidence: text.optional(),
  }),
  z.object({
    type: z.literal("lesson.schedule"),
    scheduleRevision: z.number().int().nonnegative().optional(),
    selectionMode: z.enum(["recommended", "manual"]).optional(),
    schedulingMode: z.literal("flex").optional(),
    studentId: id,
    teacherId: id,
    slots: z
      .array(
        z.object({
          date,
          time,
          teacherId: id.optional(),
          confirmedTeacher: z.boolean().optional(),
          extra: z.boolean().optional(),
          fixedOrigin: z.object({ date, time }).optional(),
        }),
      )
      .min(1),
    duration,
    plannedUnits: positive.optional(),
    kind: lessonSchema.shape.kind,
    material: text,
    confirmedTeacher: z.boolean().optional(),
    confirmationNote: text.optional(),
  }),
  z.object({
    type: z.literal("lesson.plannedUnits.update"),
    id,
    plannedUnits: positive,
  }),
  z.object({
    type: z.literal("lesson.reschedule"),
    id,
    date,
    time,
    teacherId: id,
    reason: id,
    confirmedTeacher: z.boolean().optional(),
    confirmationNote: text.optional(),
  }),
  z.object({
    type: z.literal("lesson.cancel"),
    id,
    reason: id,
    responsibility: z.enum(["学员", "老师", "平台"]),
    kind: text.optional(),
    cancelledAt: text.datetime().optional(),
    waived: z.boolean().optional(),
  }),
  z.object({
    type: z.literal("lesson.changeTeacher"),
    studentId: id,
    originalTeacherId: id,
    reason: id,
    confirmedTeacher: z.boolean().optional(),
    confirmationNote: text.optional(),
  }),
  z.object({
    type: z.literal("lesson.resolve"),
    ids: z.array(id).min(1),
    decision: z.enum(["扣课", "不扣", "缺席"]),
    reason: id,
    conclusion: text.optional(),
    minutes: nonnegative.optional(),
    units: nonnegative.optional(),
  }),
  z.object({
    type: z.literal("lesson.correct"),
    id,
    deduct: z.boolean(),
    reason: id,
    units: nonnegative.optional(),
    attendance: lessonSchema.shape.attendance.optional(),
    result: z.enum(["已完成", "缺席"]).optional(),
  }),
  z.object({ type: z.literal("lesson.link"), id, studentId: id }),
  z.object({ type: z.literal("lesson.retry"), id }),
  z.object({ type: z.literal("feedback.create"), feedback: feedbackInput }),
  z.object({
    type: z.literal("feedback.edit"),
    id,
    feedback: feedbackDetailsInputSchema,
  }),
  z.object({
    type: z.literal("feedback.customer"),
    id,
    progress: text,
    result: text,
    note: text,
  }),
  z.object({
    type: z.literal("feedback.tm"),
    id,
    jointVerdict: text,
    result: text,
    date,
    note: text,
  }),
  z.object({
    type: z.literal("feedback.followUp"),
    id,
    section: z.enum(["客服处理", "TM跟进"]),
    content: id,
  }),
  z.object({
    type: z.literal("feedback.measures"),
    id,
    measures: z.array(text),
    amount: nonnegative,
    separateDeduction: z.boolean(),
    deductionConfirmed: z.boolean(),
    note: text,
  }),
  z.object({
    type: z.literal("feedback.process"),
    id,
    note: text,
    complete: z.boolean(),
  }),
  z.object({
    type: z.literal("feedback.verdict"),
    id,
    verdict: text,
    note: text,
    measures: z.array(text),
    amount: nonnegative,
    deductionConfirmed: z.boolean(),
    separateDeduction: z.boolean().optional(),
  }),
  z.object({ type: z.literal("action.confirm"), id, approve: z.boolean() }),
  z.object({ type: z.literal("teacher.save"), teacher: teacherSchema }),
  z.object({
    type: z.literal("teacher.leave"),
    teacherId: id,
    start: id,
    end: id,
    reason: id,
    cancelLessons: z.boolean(),
  }),
  z.object({
    type: z.literal("teacher.offboard"),
    teacherId: id,
    reason: id,
  }),
  z.object({ type: z.literal("payroll.adjust"), id, amount: number, note: id }),
  z.object({
    type: z.literal("payroll.status"),
    ids: z.array(id).min(1),
    status: z.enum(["已确认", "已发放"]),
  }),
  z.object({ type: z.literal("role.save"), role: roleSchema }),
  z.object({ type: z.literal("role.delete"), id }),
  z.object({
    type: z.literal("account.save"),
    account: accountSchema,
    handoverTo: id.optional(),
    initialPassword: accountPasswordSchema.optional(),
  }),
  z.object({ type: z.literal("catalog.save"), entry: catalogSchema, projectIds: z.array(z.string()).optional() }),
  z.object({ type: z.literal("feedback-category.delete"), id }),
  z.object({ type: z.literal("rules.save"), rules: stateSchema.shape.rules }),
  z.object({
    type: z.literal("report.correct"),
    id,
    material: text,
    from: text,
    to: text,
    reason: id,
  }),
  z.object({
    type: z.literal("report.save"),
    report: reportSchema.omit({ id: true }),
  }),
  z.object({
    type: z.literal("leave.request"),
    leave: leaveSchema.omit({ id: true, status: true }),
  }),
  z.object({ type: z.literal("leave.review"), id, approve: z.boolean() }),
  z.object({ type: z.literal("language.set"), language: z.enum(["zh", "en"]) }),
]);

export function parseCommand(input: unknown): Command {
  return commandSchema.parse(input);
}
